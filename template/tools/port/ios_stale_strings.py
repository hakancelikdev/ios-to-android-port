#!/usr/bin/env python3
"""Finds Android strings still holding an OLD iOS text (same key name).

A key is "stale" when its Android value differs from today's iOS value AND iOS's git history once
contained exactly that value — i.e. the text was copied to Android and later updated on iOS.
Deliberately Android-specific texts (privacy, store name) never had that value on iOS, so they
are not reported.

Usage: python3 tools/port/ios_stale_strings.py   (run `bash tools/port/ios_ref.sh` first — must be on the reference branch)
Output: stale keys per language. Fix by hand (keep the placeholder format), or re-run the importer
if your strings are generated by ios_strings_import.py. Run it with ios_sync_scan.sh in every sync round.
"""
import glob
import html
import os
import re
import subprocess

import port_env

STRINGS_RE = re.compile(r'^"([^"]+)"\s*=\s*"((?:[^"\\]|\\.)*)";', re.M)
XML_RE = re.compile(r'<string name="([^"]+)"[^>]*>(.*?)</string>', re.S)


def _placeholders(v):
    # `%d` ↔ `%s` is not counted as a difference (Android often formats numbers as strings).
    return re.sub(r'%(\d\$)?[sd]', '%s', v).strip()


def norm_ios(v):
    v = v.replace('\\"', '"').replace('\\n', '\n')
    v = re.sub(r'%(\d\$)?@', lambda m: '%' + (m.group(1) or '') + 's', v)
    v = re.sub(r'%(\d\$)?l{0,2}d', lambda m: '%' + (m.group(1) or '') + 'd', v)
    v = v.replace('%%', '%').replace('...', '…').replace("'", '’')
    return _placeholders(v)


def norm_android(v):
    v = v.strip()
    if len(v) > 1 and v[0] == '"' and v[-1] == '"':
        v = v[1:-1]
    v = html.unescape(v).replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n')
    v = v.replace('%%', '%').replace('...', '…').replace("'", '’')
    return _placeholders(v)


def main():
    env = port_env.load()
    ios = port_env.path(env["IOS_REPO"])
    loc_rel = env.get("IOS_LOCALIZATION", "")
    res = port_env.path(env.get("ANDROID_RES", "app/src/main/res"))
    total = 0
    for lang, folder in port_env.langs(env):
        rel = os.path.join(loc_rel, f"{lang}.lproj", "Localizable.strings")
        ios_file = os.path.join(ios, rel)
        xml_files = sorted(glob.glob(os.path.join(res, folder, "strings*.xml")))
        if not os.path.exists(ios_file) or not xml_files:
            continue
        current = dict(STRINGS_RE.findall(open(ios_file, encoding="utf-8").read()))
        log = subprocess.run(['git', '-C', ios, 'log', '-p', '--format=', '--', rel],
                             capture_output=True, text=True).stdout
        history = {}
        for k, v in re.findall(r'^-"([^"]+)"\s*=\s*"((?:[^"\\]|\\.)*)";', log, re.M):
            history.setdefault(k, set()).add(norm_ios(v))
        android = {}
        for f in xml_files:
            android.update(XML_RE.findall(open(f, encoding="utf-8").read()))
        stale = [k for k, v in android.items()
                 if k in current and norm_android(v) != norm_ios(current[k])
                 and norm_android(v) in history.get(k, ())]
        total += len(stale)
        if stale:
            print(f'{lang}: ' + ' '.join(stale))
    print(f'TOTAL {total}')


if __name__ == '__main__':
    main()
