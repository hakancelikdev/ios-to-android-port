#!/usr/bin/env python3
"""iOS `Localizable.strings` (+ `.stringsdict`) → Android `res/values*/<ANDROID_STRINGS_FILE>`. Never hand-edited.

Source: <IOS_REPO>/<IOS_LOCALIZATION>/<lang>.lproj/Localizable.strings, languages from LANGS (port.env).
Conversion: `%@` → `%s` (several positionless placeholders become `%1$s`, `%2$s`…), `%n$@` → `%n$s`,
`%ld`/`%lld` → `%d`, XML/aapt escaping. Key names stay the iOS keys (R.string.<ios_key>); keys that are not valid
Android resource names (e.g. `settings.title`) are mapped to snake case (`settings_title`) and reported.
`Localizable.stringsdict` plurals → `<plurals>` (same name; call: pluralStringResource(R.plurals.x, count, args…)).

Usage: python3 tools/port/ios_strings_import.py [--allow-missing]
  --allow-missing  a key missing in a translation is skipped (Android falls back to the base language)
                   instead of failing the import.
"""
import argparse
import os
import plistlib
import re
import sys

import port_env

PAIR = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)
KEY_OK = re.compile(r"^[a-z][a-z0-9_]*$")
QUANTITIES = ["zero", "one", "two", "few", "many", "other"]
# CLDR: es/fr/it/pt have "many" (≥ 10⁶); iOS usually only gives one/other.
MANY_LOCALES = {"es", "fr", "it", "pt", "pt-BR", "pt-PT"}


def unescape(s):
    out, i = [], 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            nxt = s[i + 1]
            out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}.get(nxt, nxt))
            i += 2
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def convert_format(v):
    v = re.sub(r"%(\d+\$)?l{1,2}d", lambda m: "%" + (m.group(1) or "") + "d", v)
    plain = re.findall(r"%(?!\d+\$)@", v)
    if len(plain) > 1:
        n = [0]

        def num(_):
            n[0] += 1
            return f"%{n[0]}$s"
        v = re.sub(r"%(?!\d+\$)@", num, v)
    v = re.sub(r"%(\d+)\$@", r"%\1$s", v)
    return v.replace("%@", "%s")


def android_escape(v):
    v = v.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    v = v.replace('"', '\\"').replace("'", "\\'").replace("\n", "\\n").replace("\t", "\\t")
    if v.startswith("@") or v.startswith("?"):
        v = "\\" + v
    return v


def android_key(key):
    if KEY_OK.match(key):
        return key
    k = re.sub(r"[^a-z0-9_]", "_", key.lower())
    return k if re.match(r"^[a-z]", k) else "s_" + k


def parse(path):
    if not os.path.exists(path):
        return None
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return {m.group(1): unescape(m.group(2)) for m in PAIR.finditer(text)}


def parse_plurals(path):
    if not os.path.exists(path):
        return {}
    data = plistlib.load(open(path, "rb"))
    out = {}
    for key, entry in data.items():
        var = re.search(r"#@(\w+)@", entry["NSStringLocalizedFormatKey"]).group(1)
        rules = entry[var]
        out[key] = {q: rules[q] for q in QUANTITIES if q in rules}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-missing", action="store_true")
    args = ap.parse_args()
    env = port_env.load()
    src = port_env.path(env["IOS_REPO"], env.get("IOS_LOCALIZATION", ""))
    res = port_env.path(env.get("ANDROID_RES", "app/src/main/res"))
    out_name = env.get("ANDROID_STRINGS_FILE", "strings_ios.xml")
    langs = port_env.langs(env)

    base_lang = langs[0][0]
    base = parse(os.path.join(src, f"{base_lang}.lproj", "Localizable.strings"))
    if base is None:
        sys.exit(f"❌ base language file not found: {src}/{base_lang}.lproj/Localizable.strings")
    keymap = {k: android_key(k) for k in base}
    seen = {}
    for ios_key, a_key in keymap.items():
        if a_key in seen:
            sys.exit(f"❌ key collision after mapping: '{seen[a_key]}' and '{ios_key}' → '{a_key}'")
        seen[a_key] = ios_key
    renamed = {k: v for k, v in keymap.items() if k != v}

    for lang, folder in langs:
        table = parse(os.path.join(src, f"{lang}.lproj", "Localizable.strings"))
        if table is None:
            sys.exit(f"❌ {lang}: {lang}.lproj/Localizable.strings not found")
        missing = set(base) - set(table)
        if missing and not args.allow_missing:
            sys.exit(f"❌ {lang}: {len(missing)} missing key(s), e.g. {sorted(missing)[:5]} (--allow-missing to skip)")
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- AUTO-GENERATED by tools/port/ios_strings_import.py from the iOS Localizable.strings — DO NOT EDIT. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,TypographyEllipsis,TypographyDashes">']
        for key in base:
            if key in table:
                lines.append(f'    <string name="{keymap[key]}">{android_escape(convert_format(table[key]))}</string>')
        for key, rules in parse_plurals(os.path.join(src, f"{lang}.lproj", "Localizable.stringsdict")).items():
            lines.append(f'    <plurals name="{android_key(key)}">')
            if lang in MANY_LOCALES and "many" not in rules and "other" in rules:
                rules = {**rules, "many": rules["other"]}
            for q in [q for q in QUANTITIES if q in rules]:
                lines.append(f'        <item quantity="{q}">{android_escape(convert_format(rules[q]))}</item>')
            lines.append("    </plurals>")
        lines.append("</resources>")
        os.makedirs(os.path.join(res, folder), exist_ok=True)
        open(os.path.join(res, folder, out_name), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    if renamed:
        print(f"ℹ️  {len(renamed)} key(s) renamed to valid resource names, e.g. "
              + ", ".join(f"{k} → {v}" for k, v in list(renamed.items())[:3]))
    print(f"OK: {len(base)} keys × {len(langs)} languages → {out_name}")


if __name__ == "__main__":
    main()
